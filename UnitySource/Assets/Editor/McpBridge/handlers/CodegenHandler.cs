            {
                ["note"] = "OrderManager + OrderUI are generated by the Rust codegen module via write_file + asset_refresh."
            });
        }

        public static UnityResponse GeneratePlayerController(UnityCommand cmd)
        {
            return UnityResponse.Success(cmd.Id, new JObject
            {
                ["note"] = "PlayerController.cs is generated by the Rust codegen module via write_file + asset_refresh."
            });
        }
    }
}
